-- =============================================================================
-- AcademyOS — accounts (Better Auth) + database roles. Runs on any PostgreSQL 15+ (Neon in production).
--
-- How access works:
--   * The app connects with its owner login (DATABASE_URL). Better Auth uses that connection for the
--     auth_* tables below, which ordinary users can never read.
--   * For academy data the app switches, inside each transaction, to the restricted role
--     `authenticated` and sets `app.user_id` (see src/lib/server/db.ts → withUser). Row Level Security
--     policies call auth.uid(), which returns that id. Nothing in the browser can change it.
-- =============================================================================

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
end $$;
grant authenticated to current_user;   -- lets the app's login switch into the restricted role

create schema if not exists auth;
create or replace function auth.uid() returns uuid
language sql stable as $$ select nullif(current_setting('app.user_id', true), '')::uuid $$;
grant usage on schema auth to authenticated, anon;
grant execute on function auth.uid() to authenticated, anon;

-- ---------------------------------------------------------------- Better Auth tables
-- Generated by scripts/generate-auth-sql.mts from src/lib/server/auth-schema.ts. Do not edit by hand.
create table "auth_user" ("id" uuid default pg_catalog.gen_random_uuid() not null primary key, "name" text not null, "email" text not null unique, "email_verified" boolean not null, "image" text, "created_at" timestamptz default CURRENT_TIMESTAMP not null, "updated_at" timestamptz default CURRENT_TIMESTAMP not null, "locale" text);

create table "auth_session" ("id" uuid default pg_catalog.gen_random_uuid() not null primary key, "expires_at" timestamptz not null, "token" text not null unique, "created_at" timestamptz default CURRENT_TIMESTAMP not null, "updated_at" timestamptz not null, "ip_address" text, "user_agent" text, "user_id" uuid not null references "auth_user" ("id") on delete cascade);

create table "auth_account" ("id" uuid default pg_catalog.gen_random_uuid() not null primary key, "account_id" text not null, "provider_id" text not null, "user_id" uuid not null references "auth_user" ("id") on delete cascade, "access_token" text, "refresh_token" text, "id_token" text, "access_token_expires_at" timestamptz, "refresh_token_expires_at" timestamptz, "scope" text, "password" text, "created_at" timestamptz default CURRENT_TIMESTAMP not null, "updated_at" timestamptz not null);

create table "auth_verification" ("id" uuid default pg_catalog.gen_random_uuid() not null primary key, "identifier" text not null, "value" text not null, "expires_at" timestamptz not null, "created_at" timestamptz default CURRENT_TIMESTAMP not null, "updated_at" timestamptz default CURRENT_TIMESTAMP not null);

create table "auth_rate_limit" ("id" uuid default pg_catalog.gen_random_uuid() not null primary key, "key" text not null unique, "count" integer not null, "lastRequest" bigint not null);

create index "auth_session_user_id_idx" on "auth_session" ("user_id");

create index "auth_account_user_id_idx" on "auth_account" ("user_id");

create index "auth_verification_identifier_idx" on "auth_verification" ("identifier");

-- accounts data is private to the auth system: never reachable from the restricted roles
revoke all on auth_user, auth_session, auth_account, auth_verification, auth_rate_limit from public, authenticated, anon;

-- ordinary tables created later in public are usable by `authenticated` (RLS still decides which rows)
grant usage on schema public to authenticated;
alter default privileges in schema public grant select, insert, update, delete on tables to authenticated;
alter default privileges in schema public grant usage, select on sequences to authenticated;
